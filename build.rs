//! The protocol's types: buffa's code for the descriptors in proto/descriptors.pb (the extension protocol's
//! closure, trimmed from core's by examples/trim_descriptors.rs), with protobuf's standard JSON and reflection, so no
//! build needs protoc: `types.rs`, the module tree. And `methods.rs`, which names each rpc's JSON-RPC method and
//! says which messages are its request and its answer.

use std::fmt::Write as _;
use std::path::PathBuf;

use buffa::Message;
use buffa_descriptor::generated::descriptor::FileDescriptorSet;

const PROTOCOL: &str = "pointman/extension/v1/protocol.proto";

fn main() {
    let set = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("proto/descriptors.pb");
    println!("cargo:rerun-if-changed={}", set.display());
    let bytes = std::fs::read(&set).expect("proto/descriptors.pb is in the package");
    let fds = FileDescriptorSet::decode_from_slice(&bytes).expect("proto/descriptors.pb is a FileDescriptorSet");
    // ours, and google.type's (a task's dates, google/type/date.proto), which buffa's well-known types don't have
    let files: Vec<String> = fds
        .file
        .iter()
        .filter_map(|f| f.name.clone())
        .filter(|n| n.starts_with("pointman/") || n.starts_with("google/type/"))
        .collect();
    assert!(files.iter().any(|f| f == PROTOCOL), "{PROTOCOL} isn't in {}", set.display());
    buffa_build::Config::new()
        .descriptor_set(&set)
        .files(&files)
        .generate_views(false)
        .generate_json(true)
        .generate_reflection(true)
        .include_file("types.rs")
        .compile()
        .expect("buffa's code for pointman.extension.v1");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("methods.rs"), methods(&fds)).unwrap();
}

/// `pointman.extension.v1.PaneOpen` is `pane.open`: the first word, a dot, the rest in snake case.
fn method_name(rpc: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    for c in rpc.chars() {
        if c.is_uppercase() || words.is_empty() {
            words.push(String::new());
        }
        words.last_mut().unwrap().extend(c.to_lowercase());
    }
    match words.split_first() {
        Some((first, [])) => first.clone(),
        Some((first, rest)) => format!("{first}.{}", rest.join("_")),
        None => String::new(),
    }
}

fn methods(fds: &FileDescriptorSet) -> String {
    let file = fds.file.iter().find(|f| f.name.as_deref() == Some(PROTOCOL)).unwrap();
    let rust = |full: &str| format!("crate::types{}", full.replace('.', "::"));
    let mut out = String::from("// Generated by build.rs from proto/descriptors.pb.\n\n");
    let mut table = String::new();
    for service in &file.service {
        let side = match service.name.as_deref() {
            Some("ExtensionProcessService") => "Process",
            Some("ExtensionHostService") => "Host",
            other => panic!("a service this SDK doesn't know: {other:?}"),
        };
        for m in &service.method {
            let rpc = m.name.as_deref().unwrap();
            let name = method_name(rpc);
            let request = rust(m.input_type.as_deref().unwrap());
            let output = m.output_type.as_deref().unwrap();
            let notification = output == ".google.protobuf.Empty";
            let response = rust(output);
            if notification {
                writeln!(out, "impl crate::Notification for {request} {{\n    const METHOD: &'static str = {name:?};\n    const SIDE: crate::Side = crate::Side::{side};\n}}\n").unwrap();
                writeln!(table, "    Info {{ method: {name:?}, notification: true, side: crate::Side::{side}, round_trip: (rt::<{request}>, none) }},").unwrap();
            } else {
                writeln!(out, "impl crate::Request for {request} {{\n    const METHOD: &'static str = {name:?};\n    const SIDE: crate::Side = crate::Side::{side};\n    type Response = {response};\n}}\n").unwrap();
                writeln!(table, "    Info {{ method: {name:?}, notification: false, side: crate::Side::{side}, round_trip: (rt::<{request}>, rt::<{response}>) }},").unwrap();
            }
        }
    }
    write!(out, "/// Every method of the protocol, both ways.\npub const METHODS: &[Info] = &[\n{table}];\n").unwrap();
    out
}
